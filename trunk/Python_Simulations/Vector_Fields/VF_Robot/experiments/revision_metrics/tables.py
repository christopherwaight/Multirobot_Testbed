"""
Standalone IEEEtran tables from results/summary.json and the per-run CSVs.
Review copies only: nothing here is written into the paper .tex.
Writes tables/table_{II,III,IV,V}_revised.tex and tables/preview.tex (\\input's all four).
"""
import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
OUT = os.path.join(HERE, "tables")
NAMES = {"sink": "Sink", "source": "Source", "vortex": "Vortex", "sinking_vortex": "Sinking vortex",
         "spewing_vortex": "Spewing vortex", "saddle": "Saddle", "vortex_nn": "Vortex (reconstructed)",
         "saddle_nn": "Saddle (reconstructed)"}
LINEAR = ["sink", "source", "vortex", "sinking_vortex", "spewing_vortex", "saddle"]
HEADER = "% Generated by experiments/revision_metrics/tables.py. Review copy: not for the paper until approved.\n"


def f(x, nd=3, signed=False):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    if 0 < abs(x) < 0.5 * 10 ** -nd:
        return f"$<$0.{'0' * (nd - 1)}1"
    s = f"{x:+.{nd}f}" if signed else f"{x:.{nd}f}"
    return s.replace("-", "$-$")


def pm(a, b, nd=3, signed=False):
    return f"{f(a, nd, signed)} $\\pm$ {f(b, nd)}"


def attraction_rows(S, keys, nd):
    rows = []
    for name, s in keys:
        rows.append(" & ".join([
            name, f(s["bias"], nd), f(s["scatter"], nd), pm(s["e_mean"], s["e_sd"], nd),
            f"{f(s['e_med'], nd)} [{f(s['e_p95'], nd)}]", f(s["est_ss_mean"], nd),
            f(s["t_settle_med_5cm"], 1), f(s["E_real_mean"], 3),
            "/".join(f"{s[f'success_{t}cm']:.0f}" for t in (3, 4, 5))]) + " \\\\")
    return rows


ATT_HEAD = r"""\begin{tabular}{lcccccccc}
\hline
\textbf{Field} & \textbf{Bias} & \textbf{$\sigma$} & \textbf{$\mu_e \pm \sigma_e$} & \textbf{Median [p95]} & \textbf{Loc. error} & \textbf{$T_{\mathrm{conv}}$} & \textbf{$E_u$} & \textbf{Success (\%)} \\
 & \textbf{(m)} & \textbf{(m)} & \textbf{(m)} & \textbf{(m)} & \textbf{(m)} & \textbf{(s)} & \textbf{(m$^2$/s)} & \textbf{3/4/5 cm} \\
\hline
"""

ATT_DEF = (r"Bias is $\|\bar{\mathbf{p}}_c - \mathbf{p}^*\|$ for the mean final centroid $\bar{\mathbf{p}}_c$; "
           r"$\sigma$ is the RMS distance of the final centroids from $\bar{\mathbf{p}}_c$; "
           r"$\mu_e \pm \sigma_e$ is the mean and standard deviation of the per-trial final error "
           r"$\|\mathbf{p}_c[T] - \mathbf{p}^*\|$. Localization error is $\|\hat{\mathbf{p}}^* - \mathbf{p}^*\|$ "
           r"averaged over the last 20\% of each trial. $T_{\mathrm{conv}}$ is the median time after which the "
           r"centroid stays within 0.05~m. $E_u = \sum_j \|\mathbf{p}_c[j+1] - \mathbf{p}_c[j]\|^2/\Delta t$ is the "
           r"realized quadratic effort of the centroid. A trial fails if the centroid leaves the "
           r"1.68~m~$\times$~1.68~m map or ends farther than $\varepsilon$ from $\mathbf{p}^*$; success is "
           r"given for $\varepsilon$ = 0.03, 0.04, and 0.05~m.")


def table_II(S):
    sa = S["sim"]["attraction"]
    rows = attraction_rows(sa, [(NAMES[k], sa[k]) for k in NAMES if k in sa], 4)
    n = sa[next(iter(sa))]["n"]
    return (HEADER + "\\begin{table*}[!t]\n\\centering\n\\footnotesize\n"
            f"\\caption{{Simulated attraction across eight field types, {n} trials per field, 10~s per trial "
            f"(Coulomb robot model). {ATT_DEF}}}\n\\label{{tab:simulation_estimation_results}}\n"
            "\\setlength{\\tabcolsep}{4pt}\n" + ATT_HEAD + "\n".join(rows) + "\n\\hline\n\\end{tabular}\n\\end{table*}\n")


def table_IV(S):
    h = S["hw_attraction"]
    rows = attraction_rows(h, [(f"Saddle (printed map, {h['saddle']['n']} runs)", h["saddle"]),
                               (f"Vortex (printed map, {h['vortex']['n']} runs)", h["vortex"])], 3)
    return (HEADER + "\\begin{table*}[!t]\n\\centering\n\\footnotesize\n"
            f"\\caption{{Hardware attraction results, three robots, 10~s per run, OptiTrack metres. {ATT_DEF}}}\n"
            "\\label{tab:estimation_results}\n\\setlength{\\tabcolsep}{4pt}\n" + ATT_HEAD
            + "\n".join(rows) + "\n\\hline\n\\end{tabular}\n\\end{table*}\n")


ORB_DEF = (r"Statistics exclude the first 10~s (100 cycles). Bias is the mean of $r^* - r_d$ with "
           r"$r^* = \|\mathbf{p}_c - \mathbf{p}^*\|$, $\pm$ its standard deviation within the trajectory; "
           r"RMSE is $\sqrt{\langle (r^* - r_d)^2 \rangle}$; Ctrl.\ is the mean of $\|\mathbf{p}_c - \hat{\mathbf{p}}^*\| - r_d$, "
           r"the error relative to the estimate the controller sees. Positive bias means the cluster orbited outside $r_d$.")


def table_III(S):
    so = S["sim"]["orbit"]
    rds = sorted(so[LINEAR[0]].keys(), key=float)
    rows = []
    for rd in rds:
        lin = [so[k][rd] for k in LINEAR if k in so]
        g = dict(bias_w1=np.mean([x["bias_w1"] for x in lin]), sd_within_w1=np.mean([x["sd_within_w1"] for x in lin]),
                 rmse_w1=np.mean([x["rmse_w1"] for x in lin]), ctrl_bias_w1=np.mean([x["ctrl_bias_w1"] for x in lin]))
        cells = [rd]
        for s in (g, so["vortex_nn"][rd], so["saddle_nn"][rd]):
            cells += [pm(s["bias_w1"], s["sd_within_w1"], 3, True), f(s["rmse_w1"]), f(s["ctrl_bias_w1"], 3, True)]
        rows.append(" & ".join(cells) + " \\\\")
    n = so[LINEAR[0]][rds[0]]["n"]
    head = (r"\begin{tabular}{c|ccc|ccc|ccc}" "\n\\hline\n"
            r"\textbf{$r_d$} & \multicolumn{3}{c|}{\textbf{Linear fields (6)}} & \multicolumn{3}{c|}{\textbf{Vortex (reconstructed)}} & \multicolumn{3}{c}{\textbf{Saddle (reconstructed)}} \\" "\n"
            r"\textbf{(m)} & Bias $\pm$ std & RMSE & Ctrl. & Bias $\pm$ std & RMSE & Ctrl. & Bias $\pm$ std & RMSE & Ctrl. \\" "\n\\hline\n")
    return (HEADER + "\\begin{table*}[!t]\n\\centering\n\\footnotesize\n"
            f"\\caption{{Simulated orbital control, {n} trials per field and radius, 60~s per trial (Coulomb robot model), "
            f"radial errors in metres. {ORB_DEF} The six linear fields give identical results and are averaged.}}\n"
            "\\label{tab:simulation_orbital_results}\n\\setlength{\\tabcolsep}{3pt}\n" + head + "\n".join(rows)
            + "\n\\hline\n\\end{tabular}\n\\end{table*}\n")


def table_V(hw_orb):
    d = hw_orb[hw_orb.series.isin(["vortex", "saddle"]) & (hw_orb.rd <= 0.5 + 1e-9)]
    rds = sorted(d.rd.round(2).unique())
    rows = []
    for rd in rds:
        cells = [f"{rd:.2f}"]
        for s in ("vortex", "saddle"):
            x = d[(d.series == s) & (d.rd.round(2) == rd)]
            if len(x) == 0:
                cells += ["--"] * 5
                continue
            x = x.iloc[0]
            cells += [pm(x.bias_w1, x.sd_within_w1, 3, True), f(x.rmse_w1), f(x.ctrl_bias_w1, 3, True),
                      f"{int(x.n_laps)}", f(x.lap_mean_r_sd)]
        rows.append(" & ".join(cells) + " \\\\")
    head = (r"\begin{tabular}{c|ccccc|ccccc}" "\n\\hline\n"
            r"\textbf{$r_d$} & \multicolumn{5}{c|}{\textbf{Vortex (printed map)}} & \multicolumn{5}{c}{\textbf{Saddle (printed map)}} \\" "\n"
            r"\textbf{(m)} & Bias $\pm$ std & RMSE & Ctrl. & $N_{\mathrm{laps}}$ & Lap SD & Bias $\pm$ std & RMSE & Ctrl. & $N_{\mathrm{laps}}$ & Lap SD \\" "\n\\hline\n")
    return (HEADER + "% PROVISIONAL: old 60 s orbit logs (Simulink gains), to be replaced by the redone orbit runs.\n"
            "\\begin{table*}[!t]\n\\centering\n\\footnotesize\n"
            f"\\caption{{Hardware orbital control, three robots, one 60~s run per radius, radial errors in metres. {ORB_DEF} "
            r"$N_{\mathrm{laps}}$ counts complete revolutions after 10~s, and Lap SD is the standard deviation of the "
            r"per-lap mean radius.}" "\n"
            "\\label{tab:orbital_radius_comparison}\n\\setlength{\\tabcolsep}{3pt}\n" + head + "\n".join(rows)
            + "\n\\hline\n\\end{tabular}\n\\end{table*}\n")


def table_classification(S):
    C = S["classification"]
    conds = list(C["sim"])
    rows = []
    for f in NAMES:
        if f not in C["sim"][conds[0]]:
            continue
        cells = [NAMES[f], C["sim"][conds[0]][f]["attract"]["true_type"]]
        for c in conds:
            t = C["sim"][c][f]
            cells += [f"{100 * t['attract']['acc']:.0f}", f"{100 * t['orbit']['acc']:.0f}",
                      f"{100 * t['attract']['acc_coarse']:.0f}"]
        rows.append(" & ".join(cells) + " \\\\")
    sig = C["sigma_noise"]
    head = (r"\begin{tabular}{ll|ccc|ccc}" "\n\\hline\n"
            r" & & \multicolumn{3}{c|}{\textbf{Noise-free}} & \multicolumn{3}{c}{\textbf{Measurement noise " + f"{sig}" + r"~m/s}} \\" "\n"
            r"\textbf{Field} & \textbf{True type} & Attr. & Orbit & Coarse & Attr. & Orbit & Coarse \\" "\n\\hline\n")
    return (HEADER + "\\begin{table}[!t]\n\\centering\n\\footnotesize\n"
            r"\caption{Simulated classification accuracy (\%): the fraction of control cycles on which the type of "
            r"$\hat{\mathbf{J}}$ matches the type of the true Jacobian, over the last 2~s of attraction trials and after "
            r"10~s of orbit trials (all radii). Types follow Table~\ref{tab:field_summary}. An eigenvalue pair within "
            r"$\arcsin(\epsilon/2)$ of the imaginary (real) axis counts as a center (node), with $\epsilon$ = "
            f"{C['eps_center']}" r" (about 6$^\circ$). Coarse merges nodes and spirals "
            r"of the same stability (attracting, repelling, saddle, center). Measurement noise is white noise added to "
            r"every reading each cycle, at the size of the fixed calibration error of Section~V-A, and so exceeds the "
            r"testbed's cycle-to-cycle noise.}" "\n"
            "\\label{tab:classification}\n\\setlength{\\tabcolsep}{3pt}\n" + head + "\n".join(rows)
            + "\n\\hline\n\\end{tabular}\n\\end{table}\n")


PREVIEW = r"""\documentclass[journal]{IEEEtran}
\usepackage{amsmath,amssymb}
\makeatletter\newlabel{tab:field_summary}{{I}{1}}\makeatother
\begin{document}
\setcounter{table}{1}
\input{table_II_revised.tex}
\input{table_III_revised.tex}
\input{table_IV_revised.tex}
\input{table_V_revised.tex}
\input{table_classification_revised.tex}
\null
\end{document}
"""


def main(tag=""):
    os.makedirs(OUT, exist_ok=True)
    S = json.load(open(os.path.join(RES, f"summary{tag}.json")))
    hw_orb = pd.read_csv(os.path.join(RES, "hw_orbit_per_run.csv"))
    for name, txt in (("II", table_II(S)), ("III", table_III(S)), ("IV", table_IV(S)), ("V", table_V(hw_orb)),
                      ("classification", table_classification(S))):
        with open(os.path.join(OUT, f"table_{name}_revised.tex"), "w") as fh:
            fh.write(txt)
    with open(os.path.join(OUT, "preview.tex"), "w") as fh:
        fh.write(PREVIEW)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    import sys
    main("_quick" if "--quick" in sys.argv else "")
